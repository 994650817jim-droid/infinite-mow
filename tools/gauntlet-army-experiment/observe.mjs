// Injected only into a local QA browser. All gameplay callbacks still run once with their original arguments.
export async function instrument(page) {
  const replaceOnce = (src, orig, replacement) => {
    if (src.split(orig).length !== 2) throw Error('Missing or duplicate observation point: '+orig);
    return src.replace(orig, replacement);
  };
  await page.route(/\/src\/systems\/Legion\.ts(?:\?|$)/, async route => {
    const res = await route.fetch();
    let js = await res.text();
    js = replaceOnce(js,'damage(e, n);',`const shield = Math.max(0,e.shieldHp || 0) + (e === this.scene.boss ? Math.max(0,this.scene.bossShield||0) : 0), isBoss = e === this.scene.boss;
      damage(e, n);
      const remaining = Math.max(0,e.shieldHp||0)+(isBoss?Math.max(0,this.scene.bossShield||0):0);
      window.armyObserver?.out(u,life,e.kind,hp,spawn===e.spawnId?e.hp:0,shield,remaining);`);
    js = replaceOnce(js,'h.target.hp = Math.min(h.target.maxHp, h.target.hp + h.amount);',
      'const beforeHeal=h.target.hp; h.target.hp = Math.min(h.target.maxHp, h.target.hp + h.amount); window.armyObserver?.heal(h.owner,h.life,h.target.hp-beforeHeal);');
    // Contact currently labels a non-frontal boss sweep "boss-skill" even when generated by the contact loop.
    js = replaceOnce(js,'if (boss) this.hurtFromBoss(u, e.def.damage * BOSS_VS_TROOPS.contactMul',
      'if(window.armyObserver) window.armyObserver.contact=e.kind; if (boss) this.hurtFromBoss(u, e.def.damage * BOSS_VS_TROOPS.contactMul');
    js = replaceOnce(js,'else this.hurt(u, e.def.damage, now, { x: e.x, y: e.y, normal: true });',
      'else this.hurt(u, e.def.damage, now, { x: e.x, y: e.y, normal: true }); if(window.armyObserver) window.armyObserver.contact=null;');
    await route.fulfill({response:res,body:js});
  });
}

export function attachObserver() {
  const s=window.__game.scene.getScene('GauntletGameScene'), legion=s.legion;
  const units={}, events=[], notes=[], orderLog=[];
  const ctx=()=>({t:Math.round(s.elapsed*1000)/1000,w:s.gWave,phase:s.gPhase,order:legion.order});
  const key=(id,life)=>id+'/'+life;
  const obs=window.armyObserver={
    contact:null,source:null,
    out(u,life,kind,before,after,shield,remaining) {
      const id=key(u.id,life), hp=Math.max(0,before-Math.max(0,after)), sh=Math.max(0,shield-remaining);
      if(!units[id]) throw Error('Unregistered attacker '+id);
      units[id].dealt+=hp; units[id].shields+=sh;
      if(hp || sh) events.push({...ctx(),id,action:'out',target:kind,hp,shield:sh});
    },
    heal(u,life,amount) {const id=key(u.id,life);units[id].healed+=amount; events.push({...ctx(),id,action:'heal',hp:amount});},
    snapshot() {return {units:Object.values(units),events,notes,orderLog,totals:{army:legion.count,dead:legion.dead,recruited:legion.recruited},clock:ctx()};},
  };
  const register=(u,cost,origin)=>{
    const id=key(u.id,u.lifeId);
    if(units[id]) return false;
    units[id]={id,kind:u.kind,level:u.level,group:u.kind==='medic'?'support':u.def.ranged?'ranged':'melee',
      start:ctx(),bornHP:u.hp,cost,origin,dealt:0,shields:0,received:0,healed:0,death:null};
    return true;
  };
  for(const u of legion.units.filter(u=>u.active))register(u,0,'checkpoint');
  let purchase=null;
  const originalBuy=s.recruitTroops;
  s.recruitTroops=function(...args){
    const before=this.legion.food;
    purchase=[];
    try {
      const result=originalBuy.apply(this,args);
      if(result) {
        if(purchase.length!==3)throw Error('Unexpected recruitment batch '+purchase.length);
        const cost=before-this.legion.food;
        for(const id of purchase)units[id].cost=cost/purchase.length;
        notes.push({...ctx(),action:'purchase',cost,ids:[...purchase]});
      }
      return result;
    } finally {purchase=null;}
  };
  const recruit=legion.recruit;
  legion.recruit=function(...args) {
    const result=recruit.apply(this,args);
    if(result) for(const u of this.units.filter(u=>u.active)) {
      if(register(u,0,purchase?'purchase':'grant')&&purchase)purchase.push(key(u.id,u.lifeId));
    }
    return result;
  };
  const prev=legion.onDamageTrace;
  legion.onDamageTrace=function(ev) {
    prev?.call(this,ev);
    const id=key(ev.unit,ev.life), hurt=Math.max(0,ev.before-ev.after);
    if(!units[id])throw Error('Unregistered injured soldier '+id);
    const cause=obs.contact?(obs.contact==='boss'?'boss-contact':'contact-'+obs.contact):
      ev.cause==='ordinary'?(obs.source??'ordinary-unclassified'):ev.cause;
    units[id].received+=hurt;
    const event={...ctx(),id,action:'in',cause,before:ev.before,after:ev.after,hp:hurt};
    events.push(event);
    if(ev.after<=0)units[id].death={...ctx(),cause};
  };
  for(const [obj,method,cause] of [[s,'updateBullets','projectile'],[s.supplies,'update','supply'],[s.supplies,'resolveBodies','supply-body']]){
    if(typeof obj?.[method]!=='function')continue;
    const original=obj[method];
    obj[method]=function(...args){const prev=obs.source;obs.source=cause;try{return original.apply(this,args);}finally{obs.source=prev;}};
  }
  const originalOrder=legion.onOrder;
  legion.onOrder=function(o){originalOrder?.call(this,o);orderLog.push(ctx());};
  orderLog.push(ctx());
}
